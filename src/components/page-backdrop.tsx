/**
 * 로그인 이후 화면(목록·상세)의 배경.
 *
 * 위가 조금 진하고 아래로 갈수록 밝아져 "위에서 빛이 드는" 느낌을 준다 — 평평한 단색에는
 * 없는 깊이다. 폭은 아주 좁게 잡았다. 썸네일이 화려한 화면이라 배경이 조금만 주장해도
 * 콘텐츠와 경쟁한다.
 *
 * `fixed` 로 뷰포트에 고정한다. 문서에 붙이면 스크롤할 때 그러데이션도 함께 흘러가
 * 목록이 길수록 아래쪽이 단조로워진다. 고정해두면 어디까지 내려가도 같은 톤이 유지된다.
 *
 * `-z-10` 이 필요하다. 절대·고정 위치 요소는 일반 흐름 콘텐츠보다 위에 그려지므로,
 * 음수 z-index 로 내려야 배경 노릇을 한다(부모 배경 위, 자식 콘텐츠 아래).
 *
 * 쓰는 쪽은 배경색을 따로 깔지 않는다. 비슷한 값의 단색을 겹치면 그러데이션이 상쇄된다.
 */
export default function PageBackdrop() {
  return (
    <div
      aria-hidden="true"
      className="pointer-events-none fixed inset-0 -z-10 bg-gradient-to-b from-[#E4E8F9] via-[#F3F5FD] to-[#FDFDFF]"
    />
  );
}
